from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

from gigsaw_ai.schemas.freelancers import Freelancer, ServiceCatalogItem


class FreelancerRepository(Protocol):
    async def get(self, freelancer_id: str) -> Freelancer | None: ...
    async def list_available(self, service_category: str | None = None) -> Sequence[Freelancer]: ...
    async def list_all(self) -> Sequence[Freelancer]: ...
    async def upsert_many(self, freelancers: Sequence[Freelancer]) -> None: ...


class ServiceRepository(Protocol):
    async def get_by_categories(self, categories: Sequence[str]) -> Sequence[ServiceCatalogItem]: ...
    async def upsert_many(self, services: Sequence[ServiceCatalogItem]) -> None: ...


class ProjectRepository(Protocol):
    async def upsert(self, document: dict) -> None: ...
    async def get(self, project_id: str) -> dict | None: ...
