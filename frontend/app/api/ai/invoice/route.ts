import { NextRequest, NextResponse } from 'next/server';
import { aiClient } from '@/lib/aiClient';
import { IAiInvoiceDraft } from '@/types';

export const dynamic = 'force-dynamic';

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const {
      quotation,
      client_name,
      freelancer_name,
      invoice_number,
      tax_rate_percent = 0,
    } = body;

    if (!quotation || !client_name || !freelancer_name) {
      return NextResponse.json(
        { error: 'quotation, client_name, and freelancer_name are required.' },
        { status: 400 }
      );
    }

    const invNum = invoice_number || `INV-${new Date().getFullYear()}-${Math.floor(1000 + Math.random() * 9000)}`;

    // 1. Try FastAPI AI microservice
    try {
      const draft = await aiClient.createInvoiceDraft({
        quotation: {
          quotation_id: quotation.quotation_id || 'q-default',
          freelancer_id: quotation.freelancer_id || 'fl-default',
          work_package_id: quotation.work_package_id || 'wp-default',
          amount: quotation.amount,
          delivery_days: Number(quotation.delivery_days) || 7,
          scope: quotation.scope || 'Professional milestone deliverable',
          status: quotation.status || 'completed',
        },
        client_name,
        freelancer_name,
        invoice_number: invNum,
        tax_rate_percent,
      });

      if (draft) {
        return NextResponse.json({
          success: true,
          invoice: draft,
          source: 'fastapi_microservice',
        });
      }
    } catch (err: any) {
      console.warn('[AI Invoice] FastAPI unreachable, falling back to local invoice generator:', err.message);
    }

    // 2. High-precision Local Fallback
    const subtotal = Number(quotation.amount) || 0;
    const taxRate = Number(tax_rate_percent) || 0;
    const tax = Math.round(subtotal * (taxRate / 100) * 100) / 100;
    const total = Math.round((subtotal + tax) * 100) / 100;

    const fallbackDraft: IAiInvoiceDraft = {
      invoice_number: invNum,
      client_name,
      freelancer_name,
      currency: 'USD',
      line_items: [
        {
          description: quotation.scope || 'Professional milestone delivery & verified specifications',
          amount: subtotal.toFixed(2),
        },
      ],
      subtotal: subtotal.toFixed(2),
      tax: tax.toFixed(2),
      total: total.toFixed(2),
      payment_note: `Payment disbursed securely via Gigsaw PayPal Escrow protection. Funds released upon milestone deliverable review.`,
      disclaimer: `This invoice is auto-generated by the Gigsaw AI Assistant for merchant billing records. Applicable taxes are estimated based on local jurisdiction guidelines.`,
    };

    return NextResponse.json({
      success: true,
      invoice: fallbackDraft,
      source: 'local_engine',
    });
  } catch (error: any) {
    console.error('Error generating invoice draft:', error);
    return NextResponse.json(
      { error: error.message || 'Failed to generate invoice draft.' },
      { status: 500 }
    );
  }
}
